// Minimal DOM builder. User and page data only ever become text nodes or element properties:
// there is no way to pass HTML through this helper.

const FORBIDDEN_PROPS = new Set(['innerHTML', 'outerHTML', 'srcdoc']);

export function h(tag, props, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props || {})) {
    if (value === undefined || value === null || value === false) continue;
    if (FORBIDDEN_PROPS.has(key)) throw new Error(`h(): "${key}" is not allowed`);
    if (key === 'class') el.className = value;
    else if (key === 'text') el.textContent = String(value);
    else if (key === 'dataset') Object.assign(el.dataset, value);
    else if (key.startsWith('on')) {
      if (typeof value !== 'function') throw new Error(`h(): "${key}" must be a function`);
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else if (key === 'aria' || key === 'attrs') {
      for (const [a, v] of Object.entries(value)) el.setAttribute(key === 'aria' ? `aria-${a}` : a, String(v));
    } else if (key in el && key !== 'list' && key !== 'form') el[key] = value;
    else el.setAttribute(key, value === true ? '' : String(value));
  }
  append(el, children);
  return el;
}

export function append(parent, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false) continue;
    parent.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return parent;
}

export function clear(el) {
  while (el.firstChild) el.firstChild.remove();
  return el;
}

