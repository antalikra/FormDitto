// UI strings live in scripts/i18n/<locale>.mjs; en is the source locale. `node scripts/i18n-src.mjs`
// writes extension/_locales/*/messages.json ($1…$9 become documented chrome.i18n placeholders).
// test/unit/i18n.test.js checks that every locale has the same keys and placeholders as en.
import { writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import en from './i18n/en.mjs';
import ru from './i18n/ru.mjs';
import de from './i18n/de.mjs';
import es from './i18n/es.mjs';
import fr from './i18n/fr.mjs';
import it from './i18n/it.mjs';
import ja from './i18n/ja.mjs';
import ko from './i18n/ko.mjs';
import nl from './i18n/nl.mjs';
import pl from './i18n/pl.mjs';
import ptBR from './i18n/pt_BR.mjs';
import tr from './i18n/tr.mjs';
import uk from './i18n/uk.mjs';
import zhCN from './i18n/zh_CN.mjs';

// Chrome locale codes (folder names under _locales).
export const LOCALES = { en, ru, de, es, fr, it, ja, ko, nl, pl, pt_BR: ptBR, tr, uk, zh_CN: zhCN };

// Language picker in the panel: native names, in this order.
export const LANGUAGE_NAMES = [
  ['en', 'English'], ['de', 'Deutsch'], ['es', 'Español'], ['fr', 'Français'], ['it', 'Italiano'], ['nl', 'Nederlands'],
  ['pl', 'Polski'], ['pt_BR', 'Português (Brasil)'], ['tr', 'Türkçe'], ['uk', 'Українська'], ['ru', 'Русский'],
  ['ja', '日本語'], ['ko', '한국어'], ['zh_CN', '简体中文'],
];

// French typography: no-break space before : ; ! ? % » and after «.
const TYPOGRAPHY = {
  fr: (s) => s.replace(/« /g, '« ').replace(/ ([:;!?%»])/g, ' $1'),
};

function toChrome(text) {
  const placeholders = {};
  const message = text.replace(/\$([1-9])/g, (_, d) => {
    placeholders[`p${d}`] = { content: `$${d}` };
    return `$P${d}$`;
  });
  return Object.keys(placeholders).length ? { message, placeholders } : { message };
}

export function build() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../extension/_locales');
  // Locales removed from LOCALES must not linger in the package.
  for (const dir of readdirSync(root)) if (!LOCALES[dir]) rmSync(path.join(root, dir), { recursive: true });
  const bundle = {};
  for (const [lang, messages] of Object.entries(LOCALES)) {
    const fix = TYPOGRAPHY[lang] || ((s) => s);
    const out = {};
    bundle[lang] = {};
    for (const key of Object.keys(en)) {
      if (typeof messages[key] !== 'string') throw new Error(`${lang}: missing ${key}`);
      out[key] = toChrome(fix(messages[key]));
      bundle[lang][key] = fix(messages[key]);
    }
    const extra = Object.keys(messages).filter((k) => !(k in en));
    if (extra.length) throw new Error(`${lang}: unknown keys ${extra.join(', ')}`);
    mkdirSync(path.join(root, lang), { recursive: true });
    writeFileSync(path.join(root, lang, 'messages.json'), `${JSON.stringify(out, null, 2)}\n`);
  }
  // The panel switches language at runtime (chrome.i18n cannot), so it gets all strings as a module.
  // _locales still serves the manifest (name, description, toolbar title) and the stores.
  const names = LANGUAGE_NAMES.filter(([code]) => LOCALES[code]);
  if (names.length !== Object.keys(LOCALES).length) throw new Error('LANGUAGE_NAMES does not cover every locale');
  writeFileSync(
    path.join(root, '../lib/locales.js'),
    `// Generated by scripts/i18n-src.mjs from scripts/i18n/*.mjs. Do not edit.\n` +
      `export const LANGUAGES = ${JSON.stringify(names)};\n` +
      `export const MESSAGES = ${JSON.stringify(bundle, null, 1)};\n`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
